#!/usr/bin/env node
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const HUMAN_CODING = path.join(ROOT, 'human_coding');
const OUTPUT = path.join(ROOT, 'daemon', 'src', 'embedded-prompts.js');

const ROLES = ['arch', 'dev', 'uat'];

// Matches human_coding FIRST lines, e.g. `./team3.md` or `human_coding/team3.md`
const FIRST_LINE_RE = /^\*\*FIRST\*\*: Read `[^`]*team3\.md`[^\n]*\n/m;

const team3Content = fs.readFileSync(path.join(HUMAN_CODING, 'team3.md'), 'utf-8');

const result = {};

for (const role of ROLES) {
  const promptPath = path.join(HUMAN_CODING, `${role}_prompt.md`);
  const promptContent = fs.readFileSync(promptPath, 'utf-8');

  // Replace the FIRST line that tells agent to read team3.md with the actual content
  const merged = promptContent.replace(
    FIRST_LINE_RE,
    team3Content + '\n\n---\n\n'
  );

  if (FIRST_LINE_RE.test(merged)) {
    throw new Error(
      `${role}_prompt.md: failed to inline team3.md from human_coding/ — check FIRST line format`
    );
  }

  result[role] = merged;
}

// Escape backticks and backslashes for template literal output
function escapeForTemplate(str) {
  return str.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$/g, '\\$');
}

const output = `// AUTO-GENERATED by build/embed-prompts.js — do not edit
'use strict';

module.exports = {
  arch: \`${escapeForTemplate(result.arch)}\`,
  dev: \`${escapeForTemplate(result.dev)}\`,
  uat: \`${escapeForTemplate(result.uat)}\`,
};
`;

fs.mkdirSync(path.dirname(OUTPUT), { recursive: true });
fs.writeFileSync(OUTPUT, output, 'utf-8');

console.log(`Generated ${path.relative(ROOT, OUTPUT)} (${ROLES.length} roles)`);
